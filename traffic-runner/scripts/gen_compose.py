#!/usr/bin/env python3
"""Generate docker-compose.yml from config/devices.csv (one service per simulated device).

    python3 scripts/gen_compose.py           # validate devices.csv, write docker-compose.yml
    python3 scripts/gen_compose.py --check   # exit 1 if docker-compose.yml is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from runner import __version__  # noqa: E402
from runner.config import ConfigError, load_devices  # noqa: E402

IMAGE = f"traffic-runner:{__version__}"
COMPOSE = ROOT / "docker-compose.yml"
MEM_LIMIT = "2g"
SHM_SIZE = "1gb"
CPUS = "2.0"

HEADER = """\
# GENERATED by scripts/gen_compose.py from config/devices.csv. Do not edit by hand:
# change devices.csv and run `python3 scripts/gen_compose.py`.
#
# Every service is one simulated device with a fixed IP and MAC on the external Docker
# network `sim` (Linux bridge br-sim, 10.42.1.0/24, gateway 10.42.1.1). Create it once:
#   docker network create -o com.docker.network.bridge.name=br-sim \\
#     --subnet 10.42.1.0/24 --gateway 10.42.1.1 sim
name: traffic-runner

services:
"""

FOOTER = """\
networks:
  sim:
    external: true
"""


def service(device, build: bool) -> str:
    lines = [f"  {device.name}:", f"    image: {IMAGE}"]
    if build:
        # Build steps use the host network: with "iptables": false Docker adds no NAT for
        # its default bridge, so RUN steps on it would have no internet.
        lines += ["    build:", "      context: .", "      network: host"]
    else:
        lines += ["    pull_policy: never  # built by the first service"]
    lines += [
        f"    container_name: {device.name}",
        f"    hostname: {device.name.replace('_', '-')}",
        "    init: true",
        '    command: ["sleep", "infinity"]',
        "    restart: unless-stopped",
        "    environment:",
        f"      RUNNER_DEVICE: {device.name}",
        '      RUNNER_STRICT_IP: "1"',
        "      TZ: Europe/Zurich",
        "    dns: [10.42.1.1]",
        "    volumes:",
        "      - ./logs:/logs",
        # Code and config come from the image (Dockerfile: COPY config), so a git pull alone
        # never mixes new config with old code. Only the DNS setting is mounted.
        "      - ./config/resolv.conf:/etc/resolv.conf:ro",
        f"    shm_size: {SHM_SIZE}",
        f"    mem_limit: {MEM_LIMIT}",
        f'    cpus: "{CPUS}"',
        "    networks:",
        "      sim:",
        f"        ipv4_address: {device.ip}",
        f'        mac_address: "{device.mac}"',
        "",
    ]
    return "\n".join(lines) + "\n"


def render(devices_csv: Path | None = None) -> str:
    devices = load_devices(devices_csv)
    body = "".join(service(d, build=(i == 0)) for i, d in enumerate(devices.values()))
    return HEADER + body + FOOTER


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true", help="only check that docker-compose.yml is up to date")
    args = p.parse_args(argv)
    try:
        text = render()
    except ConfigError as e:
        print(f"devices.csv is invalid:\n{e}", file=sys.stderr)
        return 1
    if args.check:
        if not COMPOSE.exists() or COMPOSE.read_text() != text:
            print("docker-compose.yml is out of date: run python3 scripts/gen_compose.py", file=sys.stderr)
            return 1
        print("docker-compose.yml is up to date")
        return 0
    COMPOSE.write_text(text)
    print(f"wrote {COMPOSE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
