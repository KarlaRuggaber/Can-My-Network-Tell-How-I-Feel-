#!/bin/sh
# Generate .env (secrets, domain, Jitsi settings) for the peer VM. Run once.
#   ./setup.sh <public-ip>   VM in the cloud: DOMAIN=<ip-with-dashes>.sslip.io, Let's Encrypt
#   ./setup.sh --gateway     on the mini-PC next to the runner: DOMAIN=peer.sim on the docker
#                            network `peer` (br-peer, 10.43.0.0/24), Caddy's internal CA
#   ./setup.sh --local       test on a laptop: DOMAIN=peer.test, Caddy's internal CA
set -eu
cd "$(dirname "$0")"
if [ -f .env ]; then
    echo ".env already exists. Delete it to generate new secrets." >&2
    exit 1
fi
pw() { openssl rand -hex 16; }
files=jitsi-compose.yml:peer-compose.yml
memory=""
if [ "${1:-}" = "--local" ]; then
    domain=peer.test ip="" tls="tls internal" insecure=1
elif [ "${1:-}" = "--gateway" ]; then
    # videobridge address on br-peer (gateway-compose.yml); memory caps for the 7 GB mini-PC
    domain=peer.sim ip=10.43.0.13 tls="tls internal" insecure=1
    files=$files:gateway-compose.yml
    memory="JICOFO_MAX_MEMORY=512m
VIDEOBRIDGE_MAX_MEMORY=1024m"
else
    ip=${1:?usage: ./setup.sh <public-ip> | --gateway | --local}
    domain="$(echo "$ip" | tr . -).sslip.io" tls="" insecure=0
fi
token="$(pw)$(pw)"
umask 077
cat > .env <<EOF
# Generated by setup.sh. Contains secrets: never commit.
COMPOSE_FILE=$files
JITSI_IMAGE_VERSION=stable-11248
CONFIG=./jitsi-cfg
# Jitsi's own web ports only on localhost; the public entry point is Caddy (80/443).
HTTP_PORT=127.0.0.1:8000
HTTPS_PORT=127.0.0.1:8443
TZ=Europe/Zurich
DOMAIN=$domain
PUBLIC_URL=https://$domain
CADDY_TLS=$tls
DISABLE_HTTPS=1
ENABLE_HTTP_REDIRECT=0
ENABLE_LETSENCRYPT=0
# Media always through our videobridge (UDP 10000), never peer-to-peer, no external STUN.
ENABLE_P2P=false
JVB_DISABLE_STUN=true
JVB_ADVERTISE_IPS=$ip
ENABLE_PREJOIN_PAGE=false
ENABLE_WELCOME_PAGE=false
ENABLE_XMPP_WEBSOCKET=1
ENABLE_COLIBRI_WEBSOCKET=1
JICOFO_AUTH_PASSWORD=$(pw)
JVB_AUTH_PASSWORD=$(pw)
JIGASI_XMPP_PASSWORD=$(pw)
JIGASI_TRANSCRIBER_PASSWORD=$(pw)
JIBRI_RECORDER_PASSWORD=$(pw)
JIBRI_XMPP_PASSWORD=$(pw)
PEER_TOKEN=$token
PEER_INSECURE_TLS=$insecure
$memory
EOF
echo "wrote .env for https://$domain"
echo
echo "On the gateway, create /opt/can-my-network/traffic-runner/peer.env (root, mode 600) with:"
echo "  RUNNER_PEER_URL=https://$domain"
echo "  RUNNER_PEER_TOKEN=$token"
[ "$insecure" = 1 ] && echo "  RUNNER_PEER_INSECURE_TLS=1"
exit 0
